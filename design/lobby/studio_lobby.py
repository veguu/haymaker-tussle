"""Writes out/cliffside/studio_lobby.luau: the Studio (Edit mode) script that turns the uploaded GLBs into
ServerStorage.HT_Lobby.Cliffside, the model LobbyService clones into place.

    python design/lobby/studio_lobby.py

BEFORE RUNNING THE LUAU: upload export/cliffside_<n>.glb as Model assets (Open Cloud, under the group) and insert
each into ServerStorage as "LobbyImport_<n>". The script then:
  - moves every import onto its meshes' expected centres from manifest.json (an import arrives turned and
    offset; the fit is a turn about Y plus a shift, and the worst leftover distance is reported);
  - joins them as one Model whose pivot is the lobby's origin (the middle of the viewing edge, floor level),
    with x across, y up, z back from the arena, so LobbyService can drop it in with one PivotTo;
  - sets every part anchored and non-colliding (LobbyService builds the collision), shadows off for small
    pieces, cloth double-sided, lantern paper glowing;
  - clones the dressing from the existing kit (ServerStorage.HT_PropKit) at placements.json.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out", "cliffside")


def num(v):
    return str(int(v)) if float(v).is_integer() else str(round(float(v), 3))


def main():
    manifest = json.load(open(os.path.join(OUT, "manifest.json"), encoding="utf-8"))
    places = json.load(open(os.path.join(OUT, "placements.json"), encoding="utf-8"))
    mesh = ",".join(f'["{n}"]={{{num(m["x"])},{num(m["y"])},{num(m["z"])},"{m["key"]}",{m["tris"]}}}' for n, m in manifest["meshes"].items())
    place = ",".join(f'{{"{p["asset"]}",{num(p["u"])},{num(p["h"])},{num(p["d"])},{num(p["yaw"])},{num(p["scale"])}}}' for p in places)
    files = len(manifest["files"])
    lua = f'''-- GENERATED by design/lobby/studio_lobby.py: builds ServerStorage.HT_Lobby.Cliffside from the uploaded imports
local SS = game:GetService("ServerStorage")
local MESH = {{{mesh}}}
local PLACE = {{{place}}}
local FILES = {files}
local function fit(model)
	local A, E = {{}}, {{}}
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local e = MESH[p.Name]
			table.insert(A, p.Position); table.insert(E, Vector3.new(e[1], e[2], e[3]))
		end
	end
	local n = #A
	if n == 0 then return 0, 0, -1 end
	local ca, ce = Vector3.zero, Vector3.zero
	for i = 1, n do ca += A[i]; ce += E[i] end
	ca /= n; ce /= n
	local sd, sc = 0, 0
	for i = 1, n do
		local a, e = A[i] - ca, E[i] - ce
		sd += a.X * e.X + a.Z * e.Z; sc += a.Z * e.X - a.X * e.Z
	end
	local yaw = if n > 1 then math.atan2(sc, sd) else 0
	model:PivotTo(CFrame.new(ce) * CFrame.Angles(0, yaw, 0) * CFrame.new(-ca) * model:GetPivot())
	local worst = 0
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local e = MESH[p.Name]
			worst = math.max(worst, (p.Position - Vector3.new(e[1], e[2], e[3])).Magnitude)
		end
	end
	return n, math.deg(yaw), worst
end
local store = SS:FindFirstChild("HT_Lobby")
if not store then store = Instance.new("Folder"); store.Name = "HT_Lobby"; store.Parent = SS end
local old = store:FindFirstChild("Cliffside")
if old then old:Destroy() end
local model = Instance.new("Model"); model.Name = "Cliffside"
local meshes = Instance.new("Folder"); meshes.Name = "Meshes"; meshes.Parent = model
local dressing = Instance.new("Folder"); dressing.Name = "Dressing"; dressing.Parent = model
local report, seen, tris = {{}}, 0, 0
for index = 1, FILES do
	local imp = SS:FindFirstChild("LobbyImport_" .. index)
	if not imp then table.insert(report, "MISSING LobbyImport_" .. index); continue end
	for _, d in imp:GetDescendants() do if d:IsA("PackageLink") then d:Destroy() end end
	local n, yaw, worst = fit(imp)
	table.insert(report, string.format("file %d: %d meshes, turned %.1f, worst %.3f", index, n, yaw, worst))
	for _, p in imp:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local e = MESH[p.Name]
			local key = e[4]
			p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false
			p.Color = Color3.new(1, 1, 1)
			p.Material = Enum.Material.SmoothPlastic
			p.CastShadow = e[5] >= 300 and key ~= "paper"
			if key:sub(1, 5) == "cloth" then p.DoubleSided = true end
			if key == "paper" then
				p.Material = Enum.Material.Neon
				p.Color = Color3.fromRGB(255, 214, 140)
			end
			if p.Name == "Lobby_Banners_Coral" then p.TextureID = ""; p.Color = Color3.fromRGB(236, 112, 86) end
			if p.Name == "Lobby_Banners_Gold" then p.TextureID = ""; p.Color = Color3.fromRGB(238, 180, 62) end
			pcall(function() p.CollisionFidelity = Enum.CollisionFidelity.Box end)
			p.Parent = meshes
			seen += 1; tris += e[5]
		end
	end
	imp:Destroy()
end
local kit = SS:FindFirstChild("HT_PropKit")
local placed, missing = 0, {{}}
for _, s in PLACE do
	local template = kit and kit:FindFirstChild(s[1])
	if template then
		local clone = template:Clone()
		if s[6] ~= 1 then clone:ScaleTo(s[6]) end
		clone:PivotTo(CFrame.new(s[2], s[3], s[4]) * CFrame.Angles(0, s[5], 0))
		for _, p in clone:GetDescendants() do
			if p:IsA("BasePart") then p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false end
			if p:IsA("MeshPart") and (p.Name:find("^Plant_") or p.Name:find("^Flowers_")) then p.DoubleSided = true end
		end
		clone.Parent = dressing
		placed += 1
	else
		missing[s[1]] = true
	end
end
model.WorldPivot = CFrame.new()
model.Parent = store
local miss = {{}}
for name in missing do table.insert(miss, name) end
local expected = 0
for _ in MESH do expected += 1 end
return table.concat(report, "\\n") .. string.format("\\nmeshes %d of %d, %d triangles; kit pieces %d of %d%s", seen, expected, tris, placed, #PLACE, if #miss > 0 then "; kit missing: " .. table.concat(miss, ", ") else "")
'''
    path = os.path.join(OUT, "studio_lobby.luau")
    open(path, "w", encoding="utf-8", newline="\n").write(lua)
    print("wrote", path, len(lua), "chars")


if __name__ == "__main__":
    main()

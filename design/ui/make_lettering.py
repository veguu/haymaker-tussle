"""Makes the fight-poster look's lettering sheets from the mockup's own font, and the table that says where each
word is on them.

    python design/ui/make_lettering.py

Writes assets/ui/poster_titles_<n>.png (the window titles, full colour), assets/ui/poster_words_<n>.png (white on
clear, tinted in the game) and src/client/Ui/LetterRects.luau (generated: never edit it by hand). Upload the PNGs
and put their ids in src/client/Ui/Shapes.luau (`letters`). Everything is drawn at twice the mockup's size.
"""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "assets" / "ui"
PAGE = str(HERE / "poster_lettering.html")
PAD = {"titles": 28, "words": 6}


def capture(*args: str) -> str:
    done = subprocess.run(
        [sys.executable, str(HERE / "mock_capture.py"), *args], capture_output=True, timeout=180
    )
    return done.stdout.decode("utf-8", "replace")


def white(path: pathlib.Path) -> None:
    """White under every pixel, alpha only, so a tinted edge never goes dark."""
    alpha = Image.open(path).convert("RGBA").split()[-1]
    image = Image.new("RGBA", alpha.size, (255, 255, 255, 0))
    image.putalpha(alpha)
    image.save(path)


def main() -> None:
    lines = [
        "--!strict",
        "-- LetterRects - GENERATED by design/ui/make_lettering.py: never edit by hand.",
        "-- Where each word is on the lettering sheets (Ui/Shapes.letters holds the sheets' ids). A word's box is",
        "-- its text box at TWICE the mockup's size plus `pad` on every side: { sheet, x, y, width, height }.",
        "",
        "return {",
    ]
    for sheet, pad in PAD.items():
        rects = []
        for line in capture("--dump", PAGE, json.dumps({"sheet": sheet, "measure": True})).splitlines():
            if line.startswith("RECT "):
                name, numbers = line[5:].split(" | ")
                rects.append((name, [int(n) for n in numbers.split()]))
        pages = max(r[1][0] for r in rects) + 1
        for page in range(pages):
            out = OUT / f"poster_{sheet}_{page + 1}.png"
            capture("--clear", "--size", "1024,1024", "--page", PAGE, str(out), json.dumps({"sheet": sheet, "page": page}))
            if sheet == "words":
                white(out)
            print(out.name, Image.open(out).size)
        lines.append(f"\t{sheet} = {{")
        lines.append(f"\t\tpad = {pad},")
        for name, (page, x, y, w, h) in rects:
            lines.append(f'\t\t["{name}"] = {{ {page + 1}, {x}, {y}, {w}, {h} }},')
        lines.append("\t},")
        print(sheet, len(rects), "items on", pages, "page(s)")
    lines.append("}")
    (ROOT / "src" / "client" / "Ui" / "LetterRects.luau").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

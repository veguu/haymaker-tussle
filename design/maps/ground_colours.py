"""Gnomon's floor colour, sampled from its painted tiles into a coarse grid for the game's ground-break debris.

    py design/maps/ground_colours.py            -> src/shared/Config/GroundColours/Gnomon.luau

The slam debris (FxController.breakFloor) looks up the colour where it broke, so slabs and chunks are the same
green as the meadow there, or sandy on a worn earth patch. Each CELL x CELL stud cell gets the mean of its
middle half (so a cell on an earth patch's edge isn't muddied by the grass around it).

Tile layout (surfaces.surface_tiles with gnomon's TILE = 128): tile Meadow_<j><i> spans Blender
x0 = ox + i*128, y0 = oy + j*128; its image columns run +x and its rows run DOWN in y (checked by edge
continuity: right|left columns 1.7/255 apart, wrong way 11.5). Roblox: x = Blender x, z = -Blender y, about the
arena centre (the map's pivot).
"""
import math
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.join(HERE, "out", "gnomon", "textures")
OUT = os.path.join(HERE, "..", "..", "src", "shared", "Config", "GroundColours", "Gnomon.luau")

TILE = 128.0
A, B = 213.0, 176.0  # the floor's half sizes in studs (426 x 352)
CELL = 4.0
# other ground the debris can break from: one colour each (the mean of the painted pixels, not the atlas's grey
# gutter). The lip's texture is its palette strip.
PARTS = {
    "Rim_Turf_1": "Rim_Turf_1", "Rim_Turf_2": "Rim_Turf_2", "Lip_Turf": "Lip_Palette",
    "Sundial_Cap": "Sundial_Cap", "Sight_LaunchIsle_Cap": "Sight_LaunchIsle_Cap", "Fragments_Cap": "Fragments_Cap",
    "Garden_Cap": "Garden_Cap", "Islands_Cap": "Islands_Cap",
}


def part_colour(name):
    img = np.asarray(Image.open(os.path.join(TEX, f"{name}_Color.png")).convert("RGB"), np.float32).reshape(-1, 3)
    # the turf only: green pixels (the rim's cream cliff band, stone and the grey gutter left out)
    keep = img[(img[:, 1] > img[:, 0] + 8) & (img[:, 1] > img[:, 2] + 4)]
    return (keep if len(keep) else img).mean(0)


def main():
    nx, ny = math.ceil(2 * A / TILE), math.ceil(2 * B / TILE)
    ox, oy = -nx * TILE / 2, -ny * TILE / 2
    # one world image in Blender (x right, y up -> rows down), 8 px a stud
    px = None
    tiles = {}
    for j in range(ny):
        for i in range(nx):
            p = os.path.join(TEX, f"Meadow_{j}{i}_Color.png")
            if os.path.exists(p):
                tiles[(j, i)] = np.asarray(Image.open(p).convert("RGB"), np.float32)
                px = tiles[(j, i)].shape[0]
    step = TILE / px
    cols = math.ceil(2 * A / CELL)
    rows = math.ceil(2 * B / CELL)
    x_min, z_min = -cols * CELL / 2, -rows * CELL / 2
    half = int(CELL / step / 4)  # middle half of a cell, in px each side of its centre
    out = []
    fallback = None
    for r in range(rows):  # Roblox z ascending
        for c in range(cols):  # Roblox x ascending
            x = x_min + (c + 0.5) * CELL
            z = z_min + (r + 0.5) * CELL
            y = -z
            i, j = int((x - ox) // TILE), int((y - oy) // TILE)
            img = tiles.get((j, i))
            if img is None:
                out.append(None)
                continue
            col = int((x - (ox + i * TILE)) / step)
            row = int(((oy + (j + 1) * TILE) - y) / step)
            patch = img[max(row - half, 0):row + half, max(col - half, 0):col + half]
            rgb = patch.reshape(-1, 3).mean(0)
            out.append(rgb)
            fallback = rgb if fallback is None else fallback
    mean = np.mean([v for v in out if v is not None], axis=0)
    hexes = "".join(
        "%02x%02x%02x" % tuple(int(round(min(max(ch, 0), 255))) for ch in (v if v is not None else mean))
        for v in out
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- stylua: ignore start\n")
        f.write("-- GENERATED by design/maps/ground_colours.py: Gnomon's painted floor colour in a coarse grid, for the\n")
        f.write("-- ground-break debris. Cells are `cell` studs; `cols` along x, `rows` along z, from (`x0`, `z0`) about the\n")
        f.write("-- arena centre (the map's pivot), in Roblox axes; `data` is 6 hex digits (sRGB) per cell, row by row.\n")
        f.write("return {\n")
        f.write(f"\tcell = {CELL:g},\n\tcols = {cols},\n\trows = {rows},\n\tx0 = {x_min:g},\n\tz0 = {z_min:g},\n")
        f.write(f'\tdata = "{hexes}",\n')
        f.write("\tparts = {\n")
        for part, tex in PARTS.items():
            rgb = part_colour(tex)
            f.write(f'\t\t{part} = "' + "%02x%02x%02x" % tuple(int(round(ch)) for ch in rgb) + '",\n')
        f.write("\t},\n")
        f.write("}\n-- stylua: ignore end\n")
    print(f"{cols} x {rows} cells, mean sRGB {mean.round()}, {len(hexes)//1024} KB -> {OUT}")


if __name__ == "__main__":
    main()

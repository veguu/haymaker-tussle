"""Writes the Luau that assembles Gnomon in Studio (run in Edit through the Studio MCP), from the build's own data:

    python studio_dress.py            -> out/gnomon/upload/studio_map.luau, studio_dressing.luau

studio_map.luau: the two uploaded halves (ServerStorage.GnomonImport_1 / _2, inserted from Open Cloud) are turned
and moved onto their expected mesh centres (gnomon_centres.json), joined as ServerStorage.HT_Maps.Gnomon (the old
one goes to HT_MapsArchive), and set up: the floor and rim collide (hull; the two carved pond tiles precise, so the
basin is a real floor), grass double-sided without shadows, the water see-through, everything else decorative.

studio_dressing.luau: every placement (placements.json) cloned from ServerStorage.HT_PropKit into the map model's
HT_Dressing folder, turned, scaled and seated; boulders and shore rocks collide with a hull matching their shape.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out", "gnomon")
UP = os.path.join(OUT, "upload")


def lua_num(v):
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def map_script():
    c = json.load(open(os.path.join(UP, "gnomon_centres.json"), encoding="utf-8"))
    rows = ",".join(f'["{k}"]={{{lua_num(v["x"])},{lua_num(v["y"])},{lua_num(v["z"])}}}' for k, v in c.items())
    return f'''-- GENERATED by design/maps/studio_dress.py: assemble ServerStorage.HT_Maps.Gnomon from the uploaded halves
local SS = game.ServerStorage
local CENTER = Vector3.new(3000, 100, 0)
local C = {{{rows}}}
local function fit(model)
	local A, E = {{}}, {{}}
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and C[p.Name] then
			local e = C[p.Name]
			table.insert(A, p.Position); table.insert(E, CENTER + Vector3.new(e[1], e[2], e[3]))
		end
	end
	local n = #A
	local ca, ce = Vector3.zero, Vector3.zero
	for i = 1, n do ca += A[i]; ce += E[i] end
	ca /= n; ce /= n
	local sd, sc = 0, 0
	for i = 1, n do
		local a, e = A[i] - ca, E[i] - ce
		sd += a.X * e.X + a.Z * e.Z; sc += a.Z * e.X - a.X * e.Z
	end
	local yaw = math.atan2(sc, sd)
	model:PivotTo(CFrame.new(ce) * CFrame.Angles(0, yaw, 0) * CFrame.new(-ca) * model:GetPivot())
	local worst = 0
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and C[p.Name] then
			local e = C[p.Name]
			worst = math.max(worst, (p.Position - (CENTER + Vector3.new(e[1], e[2], e[3]))).Magnitude)
		end
	end
	return n, math.deg(yaw), worst
end
local report = {{}}
local maps = SS.HT_Maps
local archive = SS:FindFirstChild("HT_MapsArchive") or Instance.new("Folder")
archive.Name = "HT_MapsArchive"; archive.Parent = SS
local old = maps:FindFirstChild("Gnomon")
if old then old.Name = "Gnomon_before_kit_dressing_20261111"; old.Parent = archive end
local model = Instance.new("Model"); model.Name = "Gnomon"
local counts = {{surface = 0, grass = 0, other = 0, unmatched = 0}}
for _, name in {{"GnomonImport_1", "GnomonImport_2", "GnomonImport_3", "GnomonImport_4"}} do
	local half = SS[name]
	for _, d in half:GetDescendants() do if d:IsA("PackageLink") then d:Destroy() end end
	local n, yaw, worst = fit(half)
	report[name] = string.format("%d matched, turned %.1f, worst %.4f", n, yaw, worst)
	for _, p in half:GetDescendants() do
		if p:IsA("MeshPart") then
			if not C[p.Name] then counts.unmatched += 1 end
			-- white: an imported MeshPart keeps a grey Color that multiplies its texture (everything a third darker)
			p.Color = Color3.new(1, 1, 1)
			p.Anchored = true; p.CanTouch = false
			if p.Name:match("^Meadow_") or p.Name:match("^Rim_") then
				p.CanCollide = true; p.CanQuery = true
				-- the two carved pond tiles: precise, so the basin's bed is the floor you stand on. The rim strips
				-- too: a hull of a half-ring fills the whole half-oval and laid a flat floor over the pond.
				p.CollisionFidelity = if p.Name == "Meadow_11" or p.Name == "Meadow_12" or p.Name:match("^Rim_")
					then Enum.CollisionFidelity.PreciseConvexDecomposition else Enum.CollisionFidelity.Hull
				counts.surface += 1
			else
				p.CanCollide = false; p.CanQuery = false
				if p.Name:match("^Grass_") then
					p.CastShadow = false
					pcall(function() (p :: any).DoubleSided = true end)
					counts.grass += 1
				elseif p.Name == "Pond_Water" then
					p.Transparency = 0.22; p.CastShadow = false
				else
					counts.other += 1
				end
			end
			p.Parent = model
		end
	end
	half:Destroy()
end
model.WorldPivot = CFrame.new(CENTER)
model:SetAttribute("Source", "design/maps/out/gnomon/upload gnomon_1.glb + gnomon_2.glb (gnomon_1..4.glb, 2026-11-11 kit dressing: image-4 greens, central pond, kit grass) + HT_Dressing from placements.json")
model.Parent = maps
report.counts = counts
return report
'''


def dressing_script():
    rows = json.load(open(os.path.join(OUT, "placements.json"), encoding="utf-8"))
    data = ",".join(
        f'{{"{r["asset"]}",{lua_num(r["x"])},{lua_num(r["y"])},{lua_num(r["z"])},{lua_num(r["rot"])},{lua_num(r["scale"])},{"true" if r["collide"] else "false"},"{r["zone"]}"}}'
        for r in rows
    )
    return f'''-- GENERATED by design/maps/studio_dress.py: clone the scenery kit into the map (placements.json)
local SS = game.ServerStorage
local CENTER = Vector3.new(3000, 100, 0)
local KIT = SS.HT_PropKit
local MAP = SS.HT_Maps.Gnomon
local P = {{{data}}}
local folder = MAP:FindFirstChild("HT_Dressing")
if folder then folder:Destroy() end
folder = Instance.new("Folder"); folder.Name = "HT_Dressing"
local made, missing, solid = 0, {{}}, 0
for i, r in P do
	local src = KIT:FindFirstChild(r[1])
	if not src then missing[r[1]] = true; continue end
	local m = src:Clone()
	for _, p in m:GetDescendants() do
		if p:IsA("MeshPart") then p.Color = Color3.new(1, 1, 1) end
	end
	m.Name = string.format("%s_%03d", r[1], i)
	if math.abs(r[6] - 1) > 1e-3 then m:ScaleTo(r[6]) end
	m:PivotTo(CFrame.new(CENTER + Vector3.new(r[2], r[3], r[4])) * CFrame.Angles(0, r[5], 0))
	m:SetAttribute("Zone", r[8])
	if r[7] then
		for _, p in m:GetDescendants() do
			if p:IsA("MeshPart") then
				p.CanCollide = true; p.CanQuery = true
				p.CollisionFidelity = Enum.CollisionFidelity.Hull
				solid += 1
			end
		end
	end
	m.Parent = folder
	made += 1
	if i % 40 == 0 then task.wait() end
end
folder.Parent = MAP
local miss = {{}}
for k in missing do table.insert(miss, k) end
return {{placed = made, colliding = solid, missing = miss}}
'''


def kit_script(source_note):
    """studio_kit.luau: the uploaded kit families (ServerStorage.KitImport_rocks ... _flowers) turned onto their
    expected mesh centres and split into one Model per asset in ServerStorage.HT_PropKit, pivot at the asset's base,
    white, decorative (the dressing script turns collision on where a placement asks for it)."""
    m = json.load(open(os.path.join(UP, "kit_manifest.json"), encoding="utf-8"))
    meshes = ",".join(f'["{k}"]={{{lua_num(v["x"])},{lua_num(v["y"])},{lua_num(v["z"])},"{v["asset"]}"}}' for k, v in m["meshes"].items())
    spots = ",".join(f'["{k}"]={{{lua_num(float(v["spot"][0]))},{lua_num(float(v["spot"][1]))},{lua_num(float(v["spot"][2]))},"{v["family"]}"}}' for k, v in m["assets"].items())
    return f'''-- GENERATED by design/maps/studio_dress.py: the scenery kit's templates in ServerStorage.HT_PropKit
local SS = game.ServerStorage
local MESH = {{{meshes}}}
local SPOT = {{{spots}}}
local function fit(model)
	local A, E = {{}}, {{}}
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local e = MESH[p.Name]
			table.insert(A, p.Position); table.insert(E, Vector3.new(e[1], e[2], e[3]))
		end
	end
	local n = #A
	local ca, ce = Vector3.zero, Vector3.zero
	for i = 1, n do ca += A[i]; ce += E[i] end
	ca /= n; ce /= n
	local sd, sc = 0, 0
	for i = 1, n do
		local a, e = A[i] - ca, E[i] - ce
		sd += a.X * e.X + a.Z * e.Z; sc += a.Z * e.X - a.X * e.Z
	end
	local yaw = math.atan2(sc, sd)
	model:PivotTo(CFrame.new(ce) * CFrame.Angles(0, yaw, 0) * CFrame.new(-ca) * model:GetPivot())
	local worst = 0
	for _, p in model:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local e = MESH[p.Name]
			worst = math.max(worst, (p.Position - Vector3.new(e[1], e[2], e[3])).Magnitude)
		end
	end
	return n, math.deg(yaw), worst
end
local kit = SS:FindFirstChild("HT_PropKit")
if kit then kit:Destroy() end
kit = Instance.new("Folder"); kit.Name = "HT_PropKit"
local report, models = {{}}, {{}}
for _, fam in {{"rocks", "ruins", "trees", "plants", "flowers"}} do
	local imp = SS:FindFirstChild("KitImport_" .. fam)
	for _, d in imp:GetDescendants() do if d:IsA("PackageLink") then d:Destroy() end end
	local n, yaw, worst = fit(imp)
	report[fam] = string.format("%d meshes, turned %.1f, worst %.4f", n, yaw, worst)
	for _, p in imp:GetDescendants() do
		if p:IsA("MeshPart") and MESH[p.Name] then
			local asset = MESH[p.Name][4]
			local m = models[asset]
			if not m then m = Instance.new("Model"); m.Name = asset; models[asset] = m end
			local small = fam == "flowers" or (fam == "plants" and p.Name:match("^Plant_") ~= nil)
			p.Color = Color3.new(1, 1, 1)
			p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false
			p.CastShadow = not small
			p.Parent = m
		end
	end
	imp:Destroy()
end
local count = 0
for asset, m in models do
	local s = SPOT[asset]
	m.WorldPivot = CFrame.new(s[1], s[2], s[3])
	m:PivotTo(CFrame.new())
	m:SetAttribute("Family", s[4])
	m.Parent = kit
	count += 1
end
kit:SetAttribute("Source", "{source_note}")
kit.Parent = SS
report.assets = count
return report
'''


if __name__ == "__main__":
    import sys

    note = sys.argv[1] if len(sys.argv) > 1 else "design/maps/props_kit.py -> out/gnomon/upload/kit_*.glb"
    with open(os.path.join(UP, "studio_kit.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write(kit_script(note))
    for name, text in (("studio_map.luau", map_script()), ("studio_dressing.luau", dressing_script())):
        path = os.path.join(UP, name)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(name, len(text), "chars")

"""After a `--near` build of a suite map (only the arena's own pieces: Map 1's stud floor, 2026-11-22), writes the data
studio_map.py assembles the WHOLE map from, taking the islands from an earlier full build that is already uploaded
and in the place, so nothing unchanged is uploaded twice:

    python near_merge.py meadow_r4 meadow_r3 [meadow]      (the near build's folder, the full build's, the map id)

In <near>/ (design/maps/out/suite/):
  - manifest.json      the islands' meshes of <full> as file 1 (not a GLB: clones of the live map's own parts), then
                       the near build's GLBs as files 2..n; the near build's own manifest is kept as near_manifest.json
  - placements.json    <full>'s (the kit pieces stand on the islands)
  - landmarks.json     <full>'s (the windmill's hub, ...) with the near build's own entries laid over it
                       (floor, floor_studs); the old style's floor_detail is dropped
  - collision.json     the near build's (the new floor)
  - studio_islands_prep.luau   run in Studio (Edit) BEFORE the assembly: clones the islands' MeshParts out of
                       ServerStorage.HT_Maps.<Name> into ServerStorage.<Name>Import_1 (the assembly archives the old
                       map and builds the new one from <Name>Import_1..n, the new GLBs inserted as _2..n)
Then: python studio_map.py <map id> <near>
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SUITE_OUT = os.path.join(HERE, "..", "out", "suite")


def near_test(name):
    """The arena's own pieces of a map: what a --near build makes again (and the old style's field grass)."""
    keys = ("_Floor_", "_FloorFlowers_", "_Lip_", f"Map_{name}_Soil_", "_Crag_", "_Core_", "_FieldGrass_")
    return lambda mesh: any(k in mesh for k in keys)


def main(near, full, map_id):
    nd, fd = os.path.join(SUITE_OUT, near), os.path.join(SUITE_OUT, full)
    # a fresh near build writes manifest.json and landmarks.json anew (no "merged_from" in them): take those, so a
    # rebuild into the same folder never merges the last build's stale copies (fresh review 2026-11-22)
    kept = os.path.join(nd, "near_manifest.json")
    current = json.load(open(os.path.join(nd, "manifest.json"), encoding="utf-8"))
    if "merged_from" not in current:
        shutil.copyfile(os.path.join(nd, "manifest.json"), kept)
    elif not os.path.exists(kept):
        raise SystemExit("manifest.json is already merged and near_manifest.json is gone: rebuild the near build")
    nm = json.load(open(kept, encoding="utf-8"))
    fm = json.load(open(os.path.join(fd, "manifest.json"), encoding="utf-8"))
    name = nm["map"]
    if fm["map"] != name:
        raise SystemExit(f"different maps: {name} and {fm['map']}")
    is_near = near_test(name)
    stray = [k for k in nm["meshes"] if not is_near(k)]
    if stray:
        raise SystemExit(f"the near build holds meshes that are not the arena's own: {stray[:5]}")
    islands = {k: dict(v, file=1) for k, v in fm["meshes"].items() if not is_near(k)}
    meshes = dict(islands)
    for k, v in nm["meshes"].items():
        meshes[k] = dict(v, file=v["file"] + 1)
    files = [{"file": f"IN PLACE: the islands of {full}, cloned from ServerStorage.HT_Maps.{name}", "mb": 0, "meshes": sorted(islands)}]
    files += nm["files"]
    merged = {"map": name, "oval": nm["oval"], "merged_from": full, "meshes": meshes, "files": files,
              "triangles": sum(m["tris"] for m in meshes.values())}
    json.dump(merged, open(os.path.join(nd, "manifest.json"), "w", encoding="utf-8", newline="\n"), indent=1)
    shutil.copyfile(os.path.join(fd, "placements.json"), os.path.join(nd, "placements.json"))
    lm = json.load(open(os.path.join(fd, "landmarks.json"), encoding="utf-8"))
    lm.pop("floor_detail", None)
    near_lm_path = os.path.join(nd, "near_landmarks.json")
    current_lm = json.load(open(os.path.join(nd, "landmarks.json"), encoding="utf-8"))
    if "merged_from" not in current_lm:
        shutil.copyfile(os.path.join(nd, "landmarks.json"), near_lm_path)
    elif not os.path.exists(near_lm_path):
        raise SystemExit("landmarks.json is already merged and near_landmarks.json is gone: rebuild the near build")
    lm.update(json.load(open(near_lm_path, encoding="utf-8")))
    lm["merged_from"] = full
    json.dump(lm, open(os.path.join(nd, "landmarks.json"), "w", encoding="utf-8", newline="\n"), indent=1)
    names = ",".join(f'"{k}"' for k in sorted(islands))
    lua = f'''-- GENERATED by design/maps/suite/near_merge.py ({near} over {full}): the islands of the live map as an "import"
-- Run in Edit BEFORE studio_{map_id}.luau. Clones only: the live map is not changed (the assembly archives it).
local SS = game.ServerStorage
local live = SS.HT_Maps:FindFirstChild("{name}")
assert(live, "no HT_Maps.{name}")
local old = SS:FindFirstChild("{name}Import_1")
if old then old:Destroy() end
local NAMES = {{{names}}}
local imp = Instance.new("Model")
imp.Name = "{name}Import_1"
local missing = {{}}
for i, n in NAMES do
	local p = live:FindFirstChild(n)
	if p and p:IsA("MeshPart") then
		p:Clone().Parent = imp
	else
		table.insert(missing, n)
	end
	if i % 40 == 0 then task.wait() end
end
if #missing > 0 then
	imp:Destroy()
	error("islands missing from HT_Maps.{name}: " .. table.concat(missing, ", "))
end
imp.Parent = SS
return {{ cloned = #imp:GetChildren(), expected = #NAMES }}
'''
    open(os.path.join(nd, "studio_islands_prep.luau"), "w", encoding="utf-8", newline="\n").write(lua)
    near_tris = sum(m["tris"] for m in nm["meshes"].values())
    print(f"{near}: {len(islands)} island meshes from {full} + {len(nm['meshes'])} near meshes ({near_tris} triangles) = "
          f"{len(meshes)} meshes, {merged['triangles']} triangles; {len(files)} imports")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "meadow")

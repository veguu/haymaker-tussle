"""Map 1's POND into the place (owner 2026-11-26), swapping ONLY the meshes the pond changed, so the islands, the lip,
the soil and the rock in ServerStorage.HT_Maps.Meadow stay exactly as they are:

    python studio_pond.py meadow_r6 meadow_r5
        -> out/suite/meadow_r6/pond_patch.json (the meshes to export) and studio_pond.luau
    blender -b out/suite/meadow_r6/meadow.blend -P pond_patch_export.py -- out/suite/meadow_r6
        -> out/suite/meadow_r6/export_pond/meadow_pond.glb (the upload)

The patch = every mesh of the new build that is new (the pond's) or differs from the reference build's (triangles,
centre or size): the floor, the dirt, the stone core (its pit), the flower tiles that lost flowers. In Studio, in Edit,
with the uploaded GLB inserted as ServerStorage.MeadowPondImport, studio_pond.luau:
  1. checks the map is where its build says (two unchanged meshes on their centres), copies it to HT_MapsArchive
     (Meadow_before_pond_<time>);
  2. turns and moves the import onto the manifest's centres (studio_map.py's fit);
  3. puts each patched mesh in by name (the old one is removed): white, anchored, not colliding, queryable or
     touchable; floor meshes a flat colour with the stud Texture copied from the old floor's own HT_FloorStuds (image,
     tile, transparency: a retune in the place is kept; the grass and the dirt keep the place's own colours), offsets
     from the arena's centre (studio_map.py, MEASURED 2026-11-22); the water a flat colour, see-through, no shadow;
     the lily pads and pebbles no shadow, the reeds with; flowers no shadow;
  4. rebuilds HT_Collision from collision.json floor "tris" (the floor round the pond and the bowl) as wedges whose
     tops lie on each triangle, sloped ones too, coloured and made of what the old wedges were;
  5. removes the import and reports what it did (JSON).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SUITE = os.path.abspath(os.path.join(HERE, "..", "out", "suite"))


def num(v):
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def main(build, ref):
    out = os.path.join(SUITE, build)
    man = json.load(open(os.path.join(out, "manifest.json"), encoding="utf-8"))
    old = json.load(open(os.path.join(SUITE, ref, "near_manifest.json"), encoding="utf-8"))
    col = json.load(open(os.path.join(out, "collision.json"), encoding="utf-8"))
    lm = json.load(open(os.path.join(out, "landmarks.json"), encoding="utf-8"))
    tris = col["floor"].get("tris")
    if not tris:
        raise SystemExit("collision.json has no floor tris: was the build made with the pond?")
    pond = lm["pond"]

    def same(a, b):
        return a["tris"] == b["tris"] and all(abs(a[k] - b[k]) < 0.002 for k in ("x", "y", "z", "sx", "sy", "sz"))

    patch = sorted(n for n, m in man["meshes"].items() if n not in old["meshes"] or not same(m, old["meshes"][n]))
    kept = sorted(n for n in man["meshes"] if n not in patch)
    gone = sorted(n for n in old["meshes"] if n not in man["meshes"])
    if gone:
        raise SystemExit(f"meshes in the place that the new build no longer has: {gone}")
    json.dump({"patch": patch, "kept": kept}, open(os.path.join(out, "pond_patch.json"), "w", encoding="utf-8"), indent=1)
    centres = ",".join(f'["{n}"]={{{num(man["meshes"][n]["x"])},{num(man["meshes"][n]["y"])},{num(man["meshes"][n]["z"])}}}' for n in patch)
    probes = ",".join(f'["{n}"]={{{num(man["meshes"][n]["x"])},{num(man["meshes"][n]["y"])},{num(man["meshes"][n]["z"])}}}' for n in kept[:2])
    colours = ",".join(f'["{k}"]={{{int(r)},{int(g)},{int(b)}}}' for k, (r, g, b) in lm["floor_studs"]["colours"].items())
    flat = ",".join("{" + ",".join(num(float(c)) for v in t for c in v) + "}" for t in tris)
    w = pond["water"]
    shadow = ",".join(f'["{k}"]={"true" if v["shadow"] else "false"}' for k, v in pond["decor"].items())
    lua = f'''-- GENERATED by design/maps/suite/studio_pond.py ({build} over {ref}): Map 1's pond into ServerStorage.HT_Maps.Meadow
-- (owner 2026-11-26). Run in EDIT with the upload inserted as ServerStorage.MeadowPondImport. Only these meshes change.
local SS = game.ServerStorage
local CENTER = Vector3.new(3000, 100, 0)
local THICK = {num(float(col["floor"]["thick"]))}
local C = {{{centres}}}
local PROBE = {{{probes}}}
local TRIS = {{{flat}}}
local COLOURS = {{{colours}}}
local KEEP_COLOUR = {{ ["Map_Meadow_Floor_Grass"] = true, ["Map_Meadow_Floor_Dirt"] = true }}
local WATER = {{ name = "{w["mesh"]}", colour = {{{",".join(str(int(c)) for c in w["colour"])}}}, transparency = {num(float(w["transparency"]))} }}
local SHADOW = {{{shadow}}}
local report = {{}}
local model = SS.HT_Maps:FindFirstChild("Meadow")
assert(model, "no ServerStorage.HT_Maps.Meadow")
local imp = SS:FindFirstChild("MeadowPondImport")
assert(imp, "insert the upload as ServerStorage.MeadowPondImport first")
-- 1. the map is where its build says, and what the old floor wears (read before anything changes)
for name, e in PROBE do
	local p = model:FindFirstChild(name)
	assert(p, "missing " .. name)
	local off = (p.Position - (CENTER + Vector3.new(e[1], e[2], e[3]))).Magnitude
	assert(off < 0.05, string.format("%s is %.3f off its build centre: the map moved?", name, off))
end
local grass = model:FindFirstChild("Map_Meadow_Floor_Grass")
local studs = grass and grass:FindFirstChild("HT_FloorStuds")
assert(studs and studs:IsA("Texture"), "the old floor has no HT_FloorStuds")
local STUD = {{ texture = studs.Texture, tile = studs.StudsPerTileU, transparency = studs.Transparency }}
local oldColour = {{}}
for name in KEEP_COLOUR do
	local p = model:FindFirstChild(name)
	if p then oldColour[name] = p.Color end
end
local hit0 = model:FindFirstChild("HT_Collision")
local w0 = hit0 and hit0:FindFirstChildWhichIsA("BasePart")
local WCOLOUR = if w0 then w0.Color else Color3.fromRGB(96, 148, 89)
local WMAT = if w0 then w0.Material else Enum.Material.Grass
report.oldWedges = if hit0 then #hit0:GetChildren() else 0
local archive = SS:FindFirstChild("HT_MapsArchive") or Instance.new("Folder")
archive.Name = "HT_MapsArchive"; archive.Parent = SS
local backup = model:Clone()
backup.Name = "Meadow_before_pond_" .. os.date("!%Y%m%d%H%M")
backup.Parent = archive
report.backup = backup.Name
-- 2. the import onto its centres (studio_map.py's fit)
for _, d in imp:GetDescendants() do
	if d:IsA("PackageLink") then d:Destroy() end
	if d:IsA("BasePart") then d.PivotOffset = CFrame.new() end
end
local A, E = {{}}, {{}}
for _, p in imp:GetDescendants() do
	if p:IsA("MeshPart") and C[p.Name] then
		local e = C[p.Name]
		table.insert(A, p.Position); table.insert(E, CENTER + Vector3.new(e[1], e[2], e[3]))
	end
end
local n = #A
assert(n > 0, "no mesh of the import matches the patch")
local ca, ce = Vector3.zero, Vector3.zero
for i = 1, n do ca += A[i]; ce += E[i] end
ca /= n; ce /= n
local sd, sc = 0, 0
for i = 1, n do
	local a, e = A[i] - ca, E[i] - ce
	sd += a.X * e.X + a.Z * e.Z; sc += a.Z * e.X - a.X * e.Z
end
local yaw = if n > 1 then math.atan2(sc, sd) else 0
imp:PivotTo(CFrame.new(ce) * CFrame.Angles(0, yaw, 0) * CFrame.new(-ca) * imp:GetPivot())
local worst = 0
for _, p in imp:GetDescendants() do
	if p:IsA("MeshPart") and C[p.Name] then
		local e = C[p.Name]
		worst = math.max(worst, (p.Position - (CENTER + Vector3.new(e[1], e[2], e[3]))).Magnitude)
	end
end
report.fit = string.format("%d matched, turned %.2f, worst %.4f", n, math.deg(yaw), worst)
assert(worst < 0.05, "the import does not sit on its centres: " .. report.fit)
-- 3. the meshes, by name
local swapped, added, unmatched = {{}}, {{}}, 0
for _, p in imp:GetDescendants() do
	if not p:IsA("MeshPart") then continue end
	if not C[p.Name] then unmatched += 1; continue end
	local old = model:FindFirstChild(p.Name)
	if old then old:Destroy(); table.insert(swapped, p.Name) else table.insert(added, p.Name) end
	p.Color = Color3.new(1, 1, 1)
	p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false
	if string.find(p.Name, "_Floor_", 1, true) then
		local rgb = COLOURS[p.Name]
		p.TextureID = ""
		p.Material = Enum.Material.SmoothPlastic
		p.Color = oldColour[p.Name] or Color3.fromRGB(rgb[1], rgb[2], rgb[3])
		local t = Instance.new("Texture")
		t.Name = "HT_FloorStuds"
		t.Face = Enum.NormalId.Top
		t.Texture = STUD.texture
		t.StudsPerTileU = STUD.tile
		t.StudsPerTileV = STUD.tile
		t.Transparency = STUD.transparency
		local fromCentre = p.Position - CENTER
		t.OffsetStudsU = fromCentre:Dot(-p.CFrame.RightVector) % STUD.tile
		t.OffsetStudsV = fromCentre:Dot(p.CFrame.LookVector) % STUD.tile
		t.Parent = p
	elseif string.find(p.Name, "_FloorFlowers_", 1, true) then
		p.CastShadow = false
	elseif p.Name == WATER.name then
		p.TextureID = ""
		p.Material = Enum.Material.SmoothPlastic
		p.Color = Color3.fromRGB(WATER.colour[1], WATER.colour[2], WATER.colour[3])
		p.Transparency = WATER.transparency
		p.CastShadow = false
	elseif SHADOW[p.Name] ~= nil then
		p.CastShadow = SHADOW[p.Name]
	end
	p.Parent = model
end
report.swapped, report.added, report.unmatched = swapped, added, unmatched
-- 4. the floor's collider: the ring round the pond and the bowl, wedges whose tops lie on each triangle
local function wedge(parent)
	local w = Instance.new("WedgePart")
	w.Anchored = true; w.CanCollide = true; w.CanQuery = true; w.CanTouch = true
	w.Transparency = 1; w.CastShadow = false; w.Color = WCOLOUR; w.Material = WMAT
	w.TopSurface = Enum.SurfaceType.Smooth; w.BottomSurface = Enum.SurfaceType.Smooth
	w.Parent = parent
	return w
end
local function triangle(parent, a, b, c)
	local ab, ac, bc = b - a, c - a, c - b
	local abd, acd, bcd = ab:Dot(ab), ac:Dot(ac), bc:Dot(bc)
	if abd > acd and abd > bcd then c, a = a, c
	elseif acd > bcd and acd > abd then a, b = b, a end
	ab, ac, bc = b - a, c - a, c - b
	local right = ac:Cross(ab).Unit
	local up = bc:Cross(right).Unit
	local back = bc.Unit
	local height = math.abs(ab:Dot(up))
	local nUp = if right.Y >= 0 then right else -right
	local down = -nUp * THICK / 2
	local w1 = wedge(parent)
	w1.Size = Vector3.new(THICK, height, math.abs(ab:Dot(back)))
	w1.CFrame = CFrame.fromMatrix((a + b) / 2 + down, right, up, back)
	local w2 = wedge(parent)
	w2.Size = Vector3.new(THICK, height, math.abs(ac:Dot(back)))
	w2.CFrame = CFrame.fromMatrix((a + c) / 2 + down, -right, up, -back)
end
if hit0 then hit0:Destroy() end
local hit = Instance.new("Folder"); hit.Name = "HT_Collision"
for _, t in TRIS do
	triangle(hit, CENTER + Vector3.new(t[1], t[2], t[3]), CENTER + Vector3.new(t[4], t[5], t[6]), CENTER + Vector3.new(t[7], t[8], t[9]))
end
hit.Parent = model
report.wedges = #hit:GetChildren()
-- 5. done
imp:Destroy()
model:SetAttribute("Pond", "design/maps/out/suite/{build} (meadow.py POND, studio_pond.py), " .. os.date("!%Y-%m-%d"))
return game:GetService("HttpService"):JSONEncode(report)
'''
    path = os.path.join(out, "studio_pond.luau")
    open(path, "w", encoding="utf-8", newline="\n").write(lua)
    print("patch", len(patch), patch)
    print("kept", len(kept))
    print("wrote", path, len(lua), "chars;", len(tris), "collider triangles")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
